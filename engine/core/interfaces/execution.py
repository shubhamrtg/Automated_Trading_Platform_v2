"""Execution broker interfaces, orders, positions, and reconciliation models."""

from abc import ABC, abstractmethod
from datetime import datetime
from enum import StrEnum

from pydantic import BaseModel, Field


class OrderSide(StrEnum):
    """Order direction side."""

    BUY = "BUY"
    SELL = "SELL"


class OrderType(StrEnum):
    """Order execution type."""

    MARKET = "MARKET"
    LIMIT = "LIMIT"
    STOP = "STOP"


class OrderStatus(StrEnum):
    """Order lifecycle status."""

    PENDING = "PENDING"
    FILLED = "FILLED"
    PARTIALLY_FILLED = "PARTIALLY_FILLED"
    CANCELLED = "CANCELLED"
    REJECTED = "REJECTED"


class OrderRequest(BaseModel):
    """Order request emitted by the execution engine through RiskManager."""

    profile_id: str
    symbol: str
    side: OrderSide
    order_type: OrderType
    volume_lots: float = Field(gt=0)
    stop_loss: float | None = None
    take_profit: float | None = None
    client_order_id: str = Field(description="Unique idempotency ID generated by client/engine")
    tag: str | None = None


class OrderResult(BaseModel):
    """Result returned by broker execution."""

    client_order_id: str
    broker_order_id: str | None = None
    status: OrderStatus
    filled_volume: float = 0.0
    average_fill_price: float = 0.0
    timestamp_utc: datetime
    error_message: str | None = None


class Position(BaseModel):
    """Open position record."""

    position_id: str
    profile_id: str
    symbol: str
    side: OrderSide
    volume_lots: float = Field(gt=0)
    open_price: float = Field(gt=0)
    current_price: float = Field(gt=0)
    stop_loss: float | None = None
    take_profit: float | None = None
    unrealized_pnl: float = 0.0
    open_time_utc: datetime


class AccountState(BaseModel):
    """Account financial and margin snapshot."""

    account_id: str
    currency: str
    balance: float
    equity: float
    margin_used: float
    free_margin: float
    margin_level_percent: float | None = None
    timestamp_utc: datetime


class ReconciliationReport(BaseModel):
    """Result of continuous broker-to-engine state reconciliation."""

    timestamp_utc: datetime
    matched_positions_count: int
    untracked_broker_positions: list[Position] = Field(default_factory=list)
    missing_broker_positions: list[Position] = Field(default_factory=list)
    is_in_sync: bool = True


class ExecutionBroker(ABC):
    """Abstract interface for all broker adapters (Backtest, MT5 Demo, Live Stub)."""

    @abstractmethod
    async def connect(self) -> bool:
        """Establish connection to broker or trading environment."""
        ...

    @abstractmethod
    async def disconnect(self) -> None:
        """Gracefully disconnect from broker."""
        ...

    @abstractmethod
    async def submit_order(self, order: OrderRequest) -> OrderResult:
        """Submit an order to the execution layer."""
        ...

    @abstractmethod
    async def cancel_order(self, order_id: str) -> bool:
        """Cancel an open pending order."""
        ...

    @abstractmethod
    async def close_position(self, position_id: str) -> OrderResult:
        """Close an active position."""
        ...

    @abstractmethod
    async def get_positions(self) -> list[Position]:
        """Fetch all active positions from the broker."""
        ...

    @abstractmethod
    async def get_account_state(self) -> AccountState:
        """Fetch current balance, equity, and margin levels."""
        ...

    @abstractmethod
    async def reconcile(self, internal_positions: list[Position]) -> ReconciliationReport:
        """Compare internal engine state with broker reality."""
        ...
